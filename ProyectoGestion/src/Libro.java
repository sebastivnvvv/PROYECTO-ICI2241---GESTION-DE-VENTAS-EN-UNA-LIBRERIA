
public class Libro 
{
	private String autor;
	private String titulo;
	private String genero;
	private String isbn;
	private int precio;
	private int stock;
	
	// constructor
	public Libro(String autor, String titulo, String genero, String isbn, int precio, int stock)
	{
		this.autor = autor;
		this.titulo = titulo;
		this.genero = genero;
		this.isbn = isbn;
		this.precio = precio;
		this.stock = stock;
	}
	
}


public class Autor 
{
	// atributos
	private int id;
	private String nombre;
	
	// constructor
	public Autor(int ide, String name) 
	{
		id = ide;
		nombre = name;
	}
	
	// Metodos
	
	
	// Getters y Setters
	
	// ID
	public int getId() {
		return id;
	}
	
	public void setId(int id) {
		this.id = id;
	}
	
	// nombre
	
	public String getNombre() {
		return nombre;
	}
	
	public void setNombre(String nombre) {
		this.nombre = nombre;
	}
	
}
